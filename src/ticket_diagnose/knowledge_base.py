def search_kb(concept: str) -> Dict:
    """按故障概念精确查询一条知识条目；未命中返回空 dict。"""
    return dict(KB_ENTRIES.get(concept, {}))


def search_kb_fuzzy(text: str) -> List[Dict]:
    """按文本匹配概念名（子串命中），返回命中的多条条目。"""
    hits = []
    for concept, entry in KB_ENTRIES.items():
        if concept in text or any(k in text for k in entry.get("征兆", [])):
            hits.append({"概念": concept, **entry})
    return hits


def kb_topics() -> List[str]:
    """返回全部故障概念名（供测试 / 盘点用）。"""
    return sorted(KB_ENTRIES.keys())